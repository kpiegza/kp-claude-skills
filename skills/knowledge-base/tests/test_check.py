from __future__ import annotations

import io
import subprocess
import sys
import tempfile
import unittest
from contextlib import redirect_stderr, redirect_stdout
from pathlib import Path

from helpers import SCRIPT_PATH, import_kb, valid_note, write_note

kb = import_kb()

HEADER = "# Index\n\n<!-- Generated by kp:knowledge-base (knowledge_base.py check). Do not edit by hand. -->\n\n"


class CheckTest(unittest.TestCase):
    def setUp(self):
        self._tmp = tempfile.TemporaryDirectory()
        self.root = Path(self._tmp.name)
        (self.root / "notes").mkdir()

    def tearDown(self):
        self._tmp.cleanup()

    def note(self, name, drop=()):
        meta, body = valid_note()
        for key in drop:
            meta.pop(key)
        return kb.parse_note(write_note(self.root, name, meta, body))

    def run_main(self, argv):
        out, err = io.StringIO(), io.StringIO()
        with redirect_stdout(out), redirect_stderr(err):
            code = kb.main(argv)
        return code, out.getvalue(), err.getvalue()

    def test_empty_index(self):
        self.assertEqual(kb.render_index([]), HEADER + "_No notes yet._\n")

    def test_groups_and_sorting(self):
        notes = [self.note("redis-cache-ttl.md"), self.note("postgres-b-x.md"), self.note("postgres-a-x.md")]
        when = valid_note()[0]["when"]
        expected = (
            HEADER
            + "## postgres\n\n"
            + f"- [postgres-a-x](notes/postgres-a-x.md) · decision · 2026-11 · {when}\n"
            + f"- [postgres-b-x](notes/postgres-b-x.md) · decision · 2026-11 · {when}\n"
            + "\n## redis\n\n"
            + f"- [redis-cache-ttl](notes/redis-cache-ttl.md) · decision · 2026-11 · {when}\n"
        )
        self.assertEqual(kb.render_index(notes), expected)

    def test_missing_field_renders_question_mark(self):
        index = kb.render_index([self.note("postgres-a-x.md", drop=("when",))])
        line = next(l for l in index.splitlines() if l.startswith("- [postgres-a-x]"))
        self.assertTrue(line.endswith(" · ?"), line)

    def test_index_ignores_non_md(self):
        self.note("postgres-a-x.md")
        (self.root / "notes" / ".DS_Store").write_bytes(b"\x00")
        (self.root / "notes" / "sub").mkdir()
        write_note(self.root / "notes" / "sub", "x.md", *valid_note())
        code, _, _ = self.run_main(["check", "--root", str(self.root), "--today", "2026-11-11"])
        self.assertEqual(code, 0)
        index = (self.root / "INDEX.md").read_text(encoding="utf-8")
        self.assertIn("postgres-a-x", index)
        self.assertNotIn("DS_Store", index)
        self.assertNotIn("[x]", index)

    def test_check_writes_index_when_clean(self):
        note = self.note("postgres-a-x.md")
        code, out, _ = self.run_main(["check", "--root", str(self.root), "--today", "2026-11-11"])
        self.assertEqual(code, 0)
        self.assertEqual((self.root / "INDEX.md").read_text(encoding="utf-8"), kb.render_index([note]))
        self.assertIn("INDEX.md updated (1 notes)", out)

    def test_check_blocks_on_error(self):
        self.note("postgres-a-x.md")
        write_note(self.root, "postgres-b-x.md", None, valid_note()[1])
        code, out, _ = self.run_main(["check", "--root", str(self.root), "--today", "2026-11-11"])
        self.assertEqual(code, 1)
        self.assertIn("ERROR notes/postgres-b-x.md: no frontmatter", out)
        self.assertFalse((self.root / "INDEX.md").exists())

    def test_check_from_other_cwd(self):
        self.note("postgres-a-x.md")
        with tempfile.TemporaryDirectory() as elsewhere:
            result = subprocess.run(
                [sys.executable, str(SCRIPT_PATH), "check", "--root", str(self.root)],
                cwd=elsewhere,
                capture_output=True,
                text=True,
            )
        self.assertEqual(result.returncode, 0, result.stdout + result.stderr)
        self.assertTrue((self.root / "INDEX.md").exists())

    def test_missing_root(self):
        for command in ("check", "lint"):
            code, _, err = self.run_main([command, "--root", "/nonexistent/kb"])
            self.assertEqual(code, 2, command)
            self.assertIn("knowledge base not found: /nonexistent/kb", err)


if __name__ == "__main__":
    unittest.main()
